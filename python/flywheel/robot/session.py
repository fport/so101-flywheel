"""Splits the recording plan into sessions: each session is a few trays (6 parts laid in the tray), and a part is
used once per session.

The plan file (plans/<name>.json) is generated by `flywheel-sim plan`; it is only read here. Session boundaries
come from the same function in both the recorder (`flywheel-robot record --session N`) and the tracking site.
"""

import json
import math
from dataclasses import dataclass

from ..sim.params import REPO_ROOT

PLANS_DIR = REPO_ROOT / "plans"
TRAYS_PER_SESSION = 5  # 5 trays = 30 episodes, about 40 minutes
PHASE1_TASK = "pick the part and show it to the camera"


def phase2_task(command):
    return f"put the part in the {command.upper()} bin"


def command_onehot(command):
    """ACT command input (observation.environment_state): [ok, reject]. [0, 0] in phase 1."""
    return [1.0, 0.0] if command == "ok" else [0.0, 1.0]


@dataclass(frozen=True)
class Pick:
    plan: str
    order: str  # variant in the work order, "W" | "T"
    index: int  # position in the plan, from 0; the episode's permanent key
    tray: int  # tray number in the plan, from 1
    slot: int  # pick order within the tray, from 1
    pocket: int
    part: str
    command: str  # "ok" | "reject"
    probe: bool  # deliberately opposite command


def load_plan(name):
    return json.loads((PLANS_DIR / f"{name}.json").read_text())


def picks(name):
    plan = load_plan(name)
    out = []
    for tray in plan["trays"]:
        for slot, p in enumerate(tray["picks"], 1):
            out.append(Pick(name, plan["order"], len(out), tray["tray"], slot, p["pocket"], p["part"],
                            p["command"], p["probe"]))
    return out


def sessions(name):
    """[[tray numbers], ...]; trays are spread across sessions as evenly as possible (20 → 4 × 5, 6 → 2 × 3)."""
    trays = [t["tray"] for t in load_plan(name)["trays"]]
    n = math.ceil(len(trays) / TRAYS_PER_SESSION)
    size = math.ceil(len(trays) / n)
    return [trays[i:i + size] for i in range(0, len(trays), size)]


def tray_layout(name, tray):
    """Part IDs of the tray's 6 pockets, in pocket order (pocket 1 = left of the row nearest the arm)."""
    return next(t["pockets"] for t in load_plan(name)["trays"] if t["tray"] == tray)


def session_parts(name, session):
    """Parts the session needs, in order of first use."""
    trays = set(sessions(name)[session - 1])
    seen = []
    for p in picks(name):
        if p.tray in trays and p.part not in seen:
            seen.append(p.part)
    return seen
